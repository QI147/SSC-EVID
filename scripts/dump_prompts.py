"""Write docs/prompts.md from the code, so the documented prompts cannot drift.

    python scripts/dump_prompts.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from evid36 import evid_integrated as E36  # noqa: E402
from evid36 import fact_first as F36  # noqa: E402
from repro import ablation, runner  # noqa: E402

HEADER = """# Prompts

Generated by `scripts/dump_prompts.py` from the exact strings the code sends; do not
edit by hand. Every prompt is a single user message: the system role is empty and the
table image is attached to the same message. JSON payloads are appended after the
prompt text, one blank line apart.

Notation: `{...}`-looking text inside a prompt is literal; the only substitution is the
appended JSON data block.
"""


def block(title, note, text):
    return "\n## %s\n\n%s\n\n```text\n%s\n```\n" % (title, note, text.strip())


def main():
    parts = [HEADER]
    parts.append("\n# EVID36 method\n")
    parts.append(block("Observe facts (initial)", "`fact_first.initial`, first call.",
                       F36.OBSERVE))
    parts.append(block("Initial answer", "`fact_first.initial`, second call; receives the "
                                         "observation ledger and auxiliary results.",
                       F36.ANSWER))
    parts.append(block("Support check", "`evid_integrated.run`, phase `evidence_check`.",
                       E36.CHECK))
    parts.append(block("Directed acquisition", "`evid_integrated.run`; one directive is "
                                              "appended per gap type.",
                       E36.ACQUIRE + "\n\nACTION: <directive>"))
    for name, text in E36.DIRECTIVES.items():
        parts.append("\n**%s** — %s\n" % (name, text))
    parts.append(block("Reassess and correct", "`evid_integrated.run`, phase "
                                              "`evidence_reassess_and_correct`.",
                       E36.REPAIR))
    parts.append(block("Final gate", "`evid_integrated.run`, phase `recheck`.", E36.RECHECK))

    parts.append("\n# Baselines and controls\n")
    parts.append(block("Direct read", "arm `DIRECT`.", runner.DIRECT))
    parts.append(block("Second read with the previous answer", "arm `REREAD2`, second call.",
                       runner.REREAD))
    parts.append(block("Second read, JSON contract", "used by the budget-matched reread and "
                                                     "the ablation's no-fact-first initial.",
                       runner.REREAD_JSON))
    parts.append(block("Shared initial", "arm `COMMON`, the frozen starting point for repair.",
                       runner.COMMON))

    parts.append("\n# Ablation prompts that differ from the method\n")
    parts.append("Registered in `repro/ablation.py::PROMPT_DIFFS`.\n")
    for item in ablation.PROMPT_DIFFS:
        parts.append("\n- **%s / %s** — %s%s\n" % (
            item["arm"], item["stage"], item["change"],
            " (compatibility change)" if item["necessary"] else ""))
    parts.append(block("Check without an initial ledger", "arm `NO_FACT_FIRST`.",
                       ablation.CHECK_NO_INITIAL))
    parts.append(block("Generic re-observation", "arm `GENERIC_ACQ`.", ablation.GENERIC_ACQUIRE))
    parts.append(block("Repair without acquisition", "arm `NO_ACQ`.", ablation.REPAIR_NO_ACQ))
    parts.append(block("Gate text without acquisition", "arm `NO_ACQ`.", ablation.RECHECK_NO_ACQ))

    path = ROOT / "docs" / "prompts.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(parts), encoding="utf-8")
    print("wrote", path, len("".join(parts)), "chars")


if __name__ == "__main__":
    main()
